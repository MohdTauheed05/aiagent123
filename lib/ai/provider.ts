const providers: Record<string, AIProvider> = {
  demo: new DemoProvider(),
  openai: new OpenAIProvider(),
  anthropic: new AnthropicProvider(),
  gemini: new GeminiProvider(),
};

// Single entry point the rest of the app uses. Reads NEXT_PUBLIC_DEMO_MODE
// and NEXT_PUBLIC_AI_PROVIDER from the environment by default; the office
// UI's Demo Mode toggle passes an explicit override so switching it live in
// the browser doesn't require a rebuild.
//
// This is deliberately NEXT_PUBLIC_AI_PROVIDER, not AI_PROVIDER: every agent
// (and therefore this function) runs client-side, and Next.js only inlines
// NEXT_PUBLIC_* vars into the browser bundle — a plain AI_PROVIDER would
// silently read as undefined here. That's fine to expose; it's just a
// provider name ("openai"/"anthropic"/"gemini"), not a secret. The actual
// API keys stay server-only, read only inside app/api/ai/*/route.ts.
export function resolveProvider(forceDemo?: boolean): AIProvider {
  const envDemo = process.env.NEXT_PUBLIC_DEMO_MODE !== "false";
  const demoMode = forceDemo ?? envDemo;
  if (demoMode) return providers.demo;
  const providerName = process.env.NEXT_PUBLIC_AI_PROVIDER || "demo";
  return providers[providerName] ?? providers.demo;
}
